@logger('get meminfo')
def get_cpu_mem(packagename):
    # Obtain the usage proportion of CPU and MEM at the same time
    # RES  SHR S [%CPU] %MEM
    # RES - SHR
    # %MEM * TotalMem ≈ RES
    cmd_t = 'adb shell top -n 1| %s "%s"' % (find, packagename)
    line = os.popen(cmd_t).read().split()
    cpu_p = line[8]
    mem_p = line[9]
    return cpu_p, mem_p


