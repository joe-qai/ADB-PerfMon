@logger('Get traffic3')
def get_netflow2(pid, wlan="wlan0"):
    """A new method for calculating flow"""
    # first of collectInfo
    c1 = 'adb shell cat /proc/%s/net/dev |findstr %s' % (pid, wlan)
    line1 = os.popen(c1).read().split()
    rcv_init = line1[1]
    send_init = line1[9]
    # second of collectInfo
    c2 = 'adb shell cat /proc/%s/net/dev |findstr %s' % (pid, wlan)
    line2 = os.popen(c2).read().split()
    rcv_last = line2[1]
    send_last = line2[9]
    # count netflow
    rcv = float(rcv_last) - float(rcv_init)
    send = float(send_last) - float(send_init)
    total = rcv + send
    return rcv, send, total


