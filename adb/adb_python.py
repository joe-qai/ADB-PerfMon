@logger("Kill all processes")
def app_force_stop(package_name):
    """Stop app running"""
    cmd = 'adb shell am force-stop %s' % (package_name)
    os.system(cmd)


# 	os.system(cmd) # The return value is the exit status code of the script. There will only be 0 (success), 1,2
# 	os.popen(cmd) # Returns the output of the script execution as the return value
# 	subprocess.call('adb shell am force-stop %s' %(package_name), shell=True)


@logger("Back in the background")
def app_force_stop_hot(package_name):
    """background"""
    cmd = 'adb shell input keyevent 3'
    os.system(cmd)


@logger('Time consuming for cold start app acquisition')
def starttime_app(packagename, packagenameactivicy):  # Startup time
    # Forced exit: start/stop app
    app_force_stop(packagename)
    # start app
    cmd = 'adb shell am start -W -n %s/%s' % (packagename, packagenameactivicy)
    me = os.popen(cmd).read().split('\n')[-4].split(':')  # Get start time
    # Forced exit: start/stop app
    app_force_stop(packagename)
    return me


@logger('Time consuming for hot start app acquisition')
def starttime_app_hot(packagename, packagenameactivicy):
    """The premise must be that the app process has been started"""
    # Hot start/stop APP
    app_force_stop_hot()
    # start app
    cmd = 'adb shell am start -W -n %s/%s' % (packagename, packagenameactivicy)
    me = os.popen(cmd).read().split('\n')[-4].split(':')  # get start time
    # Hot start/stop APP
    app_force_stop_hot()
    return me


