@logger('Get traffic')
def get_netflow(packagename):
    """There is no silver here"""
    # Get the userID to start the app
    cmd = 'adb shell dumpsys package  "%s" | findstr "userId"' % (packagename)
    cm = os.popen(cmd).read().split('=')[1].strip()
    cmd1 = 'adb shell cat /proc/net/xt_qtaguid/stats |%s %s' % (find, cm)
    flow_rec1 = os.popen(cmd1).read().split()[5]  # rec
    flow_snd1 = os.popen(cmd1).read().split()[7]  # send
    cmd2 = 'adb shell cat /proc/net/xt_qtaguid/stats | %s %s' % (find, cm)
    flow_rec2 = os.popen(cmd2).read().split()[5]  # rec
    flow_snd2 = os.popen(cmd2).read().split()[7]  # send
    # The flow generated by the process is calculated as the flow after execution - the flow before execution
    netflow_rec_s = (int(flow_rec1) + int(flow_rec2))
    netflow_snd_s = (int(flow_snd1) + int(flow_snd2))
    netflow_sum = int(netflow_snd_s) - int(netflow_rec_s)
    me1 = int(flow_snd1) - int(flow_rec1)
    me2 = int(flow_snd2) - int(flow_rec2)
    return me1, me2, netflow_sum


@logger('Get traffic2')
def get_netflow1(package):
    """get total netflow; but mobilePhone not has uid_stat dir"""
    cmd = 'adb shell dumpsys package  "%s" | findstr "userId"' % (package)
    uid = os.popen(cmd).read().split('=')[1].strip()  # get application's userId
    # Get download traffic
    c = 'adb shell cat /proc/uid_stat/%s/tcp_rcv' % uid
    p1 = subprocess.Popen(c, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    print(p1.stdout.read())
    flo_rec = float(p1.stdout.read())
    # Get upload traffic
    d = 'adb shell cat /proc/uid_stat/%s/tcp_snd' % uid
    p1 = subprocess.Popen(d, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    flo_snd = float(p1.stdout.read())
    netflow_t = flo_rec + flo_snd  # download plus upload is total traffic
    return flo_snd, flo_rec, netflow_t


